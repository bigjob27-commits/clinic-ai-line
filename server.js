function splitMessage(text) {
  if (!text) return [];

  let clean = text
    .replace(/\r/g, "")
    .trim();

  // แยกตามบรรทัดที่ AI ตั้งใจแบ่งไว้
  let parts = clean
    .split(/\n+/)
    .map(x => x.trim())
    .filter(Boolean);

  // ถ้า AI ไม่ได้แบ่งบรรทัดมา
  // พยายามแบ่งตามประโยค
  if (parts.length === 1 && parts[0].length > 180) {
    parts = parts[0]
      .split(/(?<=[ค่ะครับนะคะนะครับ])\s+/)
      .map(x => x.trim())
      .filter(Boolean);
  }

  // รวมไม่ให้เกิดข้อความเล็กเกินไป
  const result = [];

  for (const part of parts) {
    if (!part) continue;

    // จำกัดความยาวแต่ละข้อความ
    if (part.length <= 500) {
      result.push(part);
    } else {
      for (let i = 0; i < part.length; i += 500) {
        result.push(part.slice(i, i + 500));
      }
    }
  }

  // ไม่ส่งเกิน 4 ข้อความต่อคำตอบ
  return result.slice(0, 4);
}



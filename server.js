// IMAGE MESSAGE
// ====================

async function handleImageMessage(messageId) {
  const image = await getLineImage(messageId);

  const aiResponse = await openai.responses.create({
    model: "gpt-6-luna",
    instructions: BEL_INSTRUCTIONS,
    input: [
      {
        role: "user",
        content: [
          {
            type: "input_text",
            text: `
ช่วยดูภาพนี้ให้หน่อยค่ะ

ถ้าเป็นอาหาร ให้ช่วยประเมินจากภาพอย่างเป็นธรรมชาติ
บอกสิ่งที่มองเห็นก่อน แล้วค่อยให้ความเห็นเบื้องต้นเกี่ยวกับมื้อนี้

อย่าประเมินปริมาณหรือคุณค่าทางโภชนาการแบบแม่นยำเกินกว่าที่ภาพสามารถบอกได้

ถ้าไม่ใช่อาหาร ให้บอกว่าเบลยังไม่เห็นอาหารในภาพ และพากลับเข้าสู่เรื่องสุขภาพของน้อง
`
          },
          {
            type: "input_image",
            image_url: `data:${image.contentType};base64,${image.base64}`
          }
        ]
      }
    ]
  });

  return aiResponse.output_text;
}



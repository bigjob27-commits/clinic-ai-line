// ======================================================
// WEBHOOK
// ======================================================

app.post("/webhook", async (req, res) => {

  try {

    console.log("LINE Webhook:");
    console.log(
      JSON.stringify(
        req.body,
        null,
        2
      )
    );

    const event =
      req.body.events?.[0];

    if (!event) {
      return res.sendStatus(200);
    }

    if (event.type !== "message") {
      return res.sendStatus(200);
    }

    const replyToken =
      event.replyToken;

    const userId =
      event.source?.userId;

    const message =
      event.message;

    console.log(
      "Message type:",
      message.type
    );


    // ==================================================
    // TEXT
    // ==================================================

    if (message.type === "text") {

      console.log(
        "User:",
        message.text
      );

      const aiText =
        await handleTextMessage(
          message.text
        );

      console.log(
        "AI:",
        aiText
      );

      await sendBellMessages(
        replyToken,
        userId,
        aiText
      );

      return res.sendStatus(200);
    }


    // ==================================================
    // IMAGE
    // ==================================================

    if (message.type === "image") {

      console.log(
        "Image message ID:",
        message.id
      );

      const aiText =
        await handleImageMessage(
          message.id
        );

      console.log(
        "AI IMAGE:",
        aiText
      );

      await sendBellMessages(
        replyToken,
        userId,
        aiText
      );

      return res.sendStatus(200);
    }


    // ==================================================
    // OTHER MESSAGE
    // ==================================================

    await replyToLine(
      replyToken,
      "เบลยังดูข้อมูลประเภทนี้ไม่ได้ค่ะ"
    );

    return res.sendStatus(200);

  } catch (error) {

    console.error(
      "ERROR:",
      error
    );

    res.sendStatus(500);
  }
});


